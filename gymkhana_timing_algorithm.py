# =====================================================================
# ШАГ 3. Трекинг мотоцикла в области интереса (ROI)
# =====================================================================
# ROI — прямоугольник вокруг створа (с запасом на подъезд/отъезд), а не
# весь кадр. Это ускоряет обработку и отсекает часть помех (другие
# райдеры вдалеке, за пределами ROI, вообще не анализируются).
#
# Внутри ROI:
#   1. Вычитание фона (MOG2) — выделяет то, что движется.
#   2. Морфологическая чистка маски: OPEN затем CLOSE.
#      ВАЖНО про размер ядра OPEN: изначально было 5x5, из-за чего тень
#      мотоцикла (особенно при низком солнце) сливалась с его силуэтом в
#      одно пятно, и точка "крайняя точка контура" иногда попадала на
#      тень, а не на колесо. Увеличение до 9x9 отсекает тонкий "хвост"
#      тени, но НЕ срезает реальные детали вроде колеса на кадрах, где
#      мотоцикл близко к камере (проверено визуально). Дальнейшее
#      увеличение (15+) уже портит детекцию колеса на крупных планах —
#      9 оказалось разумным компромиссом.
#   3. Берется самый большой контур на кадре.
#   4. В нижней полосе контура (около уровня земли, ±15px от нижней
#      точки) находятся две крайние точки — самая левая и самая правая.
#      Это грубая эвристика "точка контакта колеса с асфальтом" с двух
#      возможных сторон объекта.
#   5. По знаку скорости смещения центра масс между кадрами определяется
#      направление движения, и в качестве рабочей "точки колеса" берется
#      та из двух крайних точек, что находится по ходу движения
#      (leading edge) — та, что ближе к тому месту, куда байк едет.

def track(video_path, roi, static_end_frame, open_kernel=9, min_area=300):
    """
    roi: (x0, y0, x1, y1) в пикселях кадра.
    static_end_frame: кадр, дальше которого не обрабатываем (см. Шаг 1).
    Возвращает список словарей с детекциями по кадрам.
    """
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS)
    x0, y0, x1, y1 = roi
    back_sub = cv2.createBackgroundSubtractorMOG2(
        history=200, varThreshold=28, detectShadows=False
    )
    records = []
    frame_idx = 0
    while True:
        ret, frame = cap.read()
        if not ret or frame_idx >= static_end_frame:
            break
        roi_frame = frame[y0:y1, x0:x1]
        fg = back_sub.apply(roi_frame)
        fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, np.ones((open_kernel, open_kernel), np.uint8))
        fg = cv2.morphologyEx(fg, cv2.MORPH_CLOSE, np.ones((15, 15), np.uint8))

        contours, _ = cv2.findContours(fg, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        best, best_area = None, 0
        for c in contours:
            a = cv2.contourArea(c)
            if a > best_area:
                best_area, best = a, c

        # frame_idx > 0: первый кадр — это ещё "холодный старт" модели
        # фона (MOG2 без истории считает почти всё передним планом),
        # его детекцию отбрасываем.
        if best is not None and best_area > min_area and frame_idx > 0:
            M = cv2.moments(best)
            cx = M["m10"] / M["m00"] + x0
            cy = M["m01"] / M["m00"] + y0

            pts = best.reshape(-1, 2)
            y_max = pts[:, 1].max()
            band = pts[pts[:, 1] >= y_max - 15]
            left_bottom = band[band[:, 0].argmin()] + [x0, y0]
            right_bottom = band[band[:, 0].argmax()] + [x0, y0]

            records.append({
                "frame": frame_idx,
                "t": frame_idx / fps,
                "cx": cx, "cy": cy,
                "area": best_area,
                "left_bottom": left_bottom.tolist(),
                "right_bottom": right_bottom.tolist(),
            })
        frame_idx += 1
    cap.release()
    return records


# =====================================================================
# ШАГ 4. Фильтрация "настоящих" проездов + поиск момента пересечения
# =====================================================================
# Кадры с детекцией группируются в сегменты присутствия объекта в ROI
# (разрыв > 5 кадров между детекциями — новый сегмент). Байк может
# несколько раз проезжать рядом с краем ROI во время самой фигуры, не
# пересекая створ по-настоящему — такие сегменты отсекаются по площади
# пятна: настоящий проезд ЧЕРЕЗ створ даёт заметно большую площадь
# (десятки тысяч px², потому что байк оказывается близко к камере),
# чем случайный проезд по касательной к границе ROI.
#
# AREA_THRESH подобран эмпирически (~8000 px²) — работает на всех 4
# проверенных видео, но не универсален, при другом расстоянии камеры до
# створа его может понадобиться пересчитать.
#
# Внутри каждого "настоящего" сегмента ищется смена знака расстояния до
# линии между соседними кадрами, момент пересечения находится ЛИНЕЙНОЙ
# ИНТЕРПОЛЯЦИЕЙ между двумя кадрами — это и даёт точность выше, чем шаг
# между кадрами (при 30 fps это доли из ~33мс, а не целые 33мс).

def analyze(records, p1, p2, area_thresh=8000):
    """
    p1, p2: две точки линии старта-финиша, см. Шаг 2.
    Возвращает список времён всех найденных пересечений линии (в секундах).
    """
    p1 = np.array(p1, dtype=float)
    p2 = np.array(p2, dtype=float)

    frames = np.array([r["frame"] for r in records])
    times = np.array([r["t"] for r in records])
    cx = np.array([r["cx"] for r in records])
    area = np.array([r["area"] for r in records])
    left_bottom = np.array([r["left_bottom"] for r in records])
    right_bottom = np.array([r["right_bottom"] for r in records])

    d = p2 - p1
    d = d / np.linalg.norm(d)
    normal = np.array([-d[1], d[0]])

    def signed_distance(pts):
        return (pts - p1) @ normal

    # разбивка на сегменты присутствия в ROI
    segments = []
    seg_start = 0
    for i in range(1, len(frames)):
        if frames[i] - frames[i-1] > 5:
            segments.append((seg_start, i-1))
            seg_start = i
    segments.append((seg_start, len(frames)-1))

    real_segments = [(s, e) for s, e in segments if area[s:e+1].max() > area_thresh]

    # выбор "точки колеса по ходу движения" и расстояние до линии
    dist_leading = np.full(len(frames), np.nan)
    for s, e in real_segments:
        seg_cx = cx[s:e+1]
        vx = np.gradient(seg_cx)
        for k, i in enumerate(range(s, e+1)):
            pt = right_bottom[i] if vx[k] > 0 else left_bottom[i]
            dist_leading[i] = signed_distance(pt)

    # поиск смены знака + линейная интерполяция момента пересечения
    crossings = []
    for s, e in real_segments:
        seg_dist = dist_leading[s:e+1]
        seg_times = times[s:e+1]
        for i in range(1, len(seg_dist)):
            if np.isnan(seg_dist[i-1]) or np.isnan(seg_dist[i]):
                continue
            if (seg_dist[i-1] > 0) != (seg_dist[i] > 0):
                d0, d1 = seg_dist[i-1], seg_dist[i]
                t0, t1 = seg_times[i-1], seg_times[i]
                frac = -d0 / (d1 - d0)
                crossings.append(t0 + frac * (t1 - t0))
    return crossings


# =====================================================================
# ШАГ 5. Выбор старта и финиша из списка пересечений
# =====================================================================
# На старте и финише часто вместо одного четкого пересечения возникает
# ПАЧКА из нескольких (байк покачивается на старте / медленно маневрирует
# у линии на финише, вместо чистого быстрого проезда).
#
# Рабочая эмпирическая эвристика (проверена на 4 видео, каждый раз
# попадала в пределы ~0.5с от референсного времени):
#   СТАРТ  = ПОСЛЕДНЕЕ пересечение в первой пачке (окончательный момент,
#            когда байк уезжает от линии, не возвращаясь).
#   ФИНИШ  = ПЕРВОЕ пересечение в последней пачке (момент реального
#            завершения проезда; последующие пересечения обычно — байк
#            докатывается/поправляется прямо у линии уже после финиша).

def pick_start_finish(crossings, split_seconds=10.0):
    """
    Простое разделение "стартовая пачка" / "финишная пачка" по времени:
    всё, что произошло в первые split_seconds секунд — старт, всё
    остальное — финиш. Работает, когда заезд длится намного дольше
    split_seconds (у нас круги были 60-70+ секунд). Для очень коротких
    заездов эту границу нужно будет пересмотреть.
    """
    start_candidates = [c for c in crossings if c < split_seconds]
    finish_candidates = [c for c in crossings if c >= split_seconds]
    if not start_candidates or not finish_candidates:
        return None, None
    return max(start_candidates), min(finish_candidates)


