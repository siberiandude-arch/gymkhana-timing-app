"""
Алгоритм замера времени в мото-джимхане по видео со статичной камеры.
=======================================================================

ЧТО ЭТО
Прототип на Python/OpenCV, который по видео заезда (телефон на стойке)
автоматически считает время прохождения старт-финишного створа —
без телеметрии и лазерных ворот.

СТАТУС
Проверено на 4 реальных заездах с разных площадок. Точность относительно
референсного времени с табло телеметрии — от ~0.05 до ~0.55 секунды,
в среднем около 0.25 секунды. Ни одного грубого промаха.

ЦЕЛЬ ЭТОГО ФАЙЛА
Дать разработчику/агенту (например, Claude Code) рабочую логику для
портирования в мобильное приложение (iOS/Android) — не описание "как я это
себе представляю", а код, который реально запускался и был проверен на
реальных видео.

ВХОДНЫЕ ПРЕДПОЛОЖЕНИЯ
- Камера неподвижна на протяжении всего заезда (на стойке/штативе).
- Старт и финиш — один и тот же створ (выехал за линию — заехал обратно).
- У створа есть меловая/покрасочная линия на асфальте, конусы стоят рядом,
  но НЕ всегда точно на ней (это важно, см. раздел "Калибровка линии" ниже).
- Видео 30 fps, 1920x1080 (типичная съемка на телефон).

ЧЕГО ТУТ НЕТ (сознательно за пределами MVP)
- Детекция сбитых конусов, касания ногой асфальта, корректного выезда из
  финишных ворот.
- Работа в реальном времени на телефоне (это next step, не часть прототипа).
- Автоматическая калибровка линии (см. ниже, делается вручную по кадру).

ИЗВЕСТНЫЕ НЕРЕШЕННЫЕ ВОПРОСЫ
1. По регламенту телеметрия часто висит на высоте 300-550мм (например,
   на макушке конуса), а не на земле. Пробовали поднять точку трекинга
   до высоты макушки конуса — результат неожиданно стал ХУЖЕ, а не лучше.
   Причина не найдена, тема отложена. Сейчас трекается точка на уровне
   земли (контакт колеса с асфальтом), и это стабильно дает разумную
   точность, несмотря на теоретическое несоответствие регламенту.
2. Автоматическая детекция конусов по цвету (HSV-порог по оранжевому)
   пробовалась — работает нестабильно (недомеряет высоту из-за освещения).
   Калибровка линии сейчас делается вручную по крупному кропу кадра.
3. Порог площади пятна для фильтрации "настоящих" проездов через створ
   (AREA_THRESH) подобран эмпирически и не универсален.
"""

import cv2
import numpy as np
import json


# =====================================================================
# ШАГ 1. Определение статичного участка видео
# =====================================================================
# Люди обычно снимают весь заезд на штативе, а в конце берут камеру в
# руки, чтобы снять табло телеметрии крупным планом (это и есть тот самый
# кадр, который нужен по регламенту My Gymkhana Cup). Дальше этот момент
# обрабатывать не нужно — там уже не сцена с трассой, а крупный план.
#
# Метод: сравниваем соседние кадры (уменьшенные, разбитые на блоки 6x6,
# берем МЕДИАНУ по блокам — это устойчиво к тому, что в кадре двигается
# один небольшой объект вроде мотоцикла, а не вся сцена).

def detect_static_camera_end(video_path, threshold=3.0, min_run=10):
    """
    Возвращает номер кадра, начиная с которого камера перестает быть
    статичной (человек взял её в руки), или None, если движения не найдено.
    """
    cap = cv2.VideoCapture(video_path)
    prev_gray = None
    diffs = []
    scale = 0.25
    while True:
        ret, frame = cap.read()
        if not ret:
            break
        small = cv2.resize(frame, None, fx=scale, fy=scale)
        gray = cv2.cvtColor(small, cv2.COLOR_BGR2GRAY)
        if prev_gray is not None:
            diff = cv2.absdiff(gray, prev_gray)
            h, w = diff.shape
            bh, bw = h // 6, w // 6
            block_means = [
                diff[by*bh:(by+1)*bh, bx*bw:(bx+1)*bw].mean()
                for by in range(6) for bx in range(6)
            ]
            diffs.append(np.median(block_means))
        else:
            diffs.append(0)
        prev_gray = gray
    cap.release()

    diffs = np.array(diffs)
    above = diffs > threshold
    run = 0
    for i, a in enumerate(above):
        if a:
            run += 1
            if run >= min_run:
                return i - min_run + 1
        else:
            run = 0
    return None


