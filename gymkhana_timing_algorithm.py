# ШАГ 2. Калибровка линии старта-финиша — ВАЖНО, читать перед использованием
# =====================================================================
# Линия задается ДВУМЯ ТОЧКАМИ (P1, P2) в пикселях кадра.
#
# КЛЮЧЕВОЙ УРОК ИЗ ТЕСТИРОВАНИЯ: калибровать нужно ПО САМОЙ МЕЛОВОЙ/
# ПОКРАСОЧНОЙ ЛИНИИ НА АСФАЛЬТЕ, а не по основанию конусов на глаз.
# Конусы стоят РЯДОМ с линией, но не идеально на ней. Калибровка "по
# конусам" на глаз стабильно давала систематическую ошибку 10-20 пикселей,
# что превращалось в заметные доли секунды в итоговом времени.
#
# Практический способ: взять чистый кадр без мотоцикла в кадре, сделать
# крупный кроп (x3-x5) области вокруг обоих конусов по отдельности, и
# найти на асфальте именно тонкую покрасочную линию, а не основание
# резинового конуса.
#
# В мобильном приложении это должно быть интерактивной калибровкой:
# пользователь сам тапает две точки на превью с камеры перед стартом.
#
# Примеры откалиброванных линий с 4 проверенных видео (для справки, НЕ
